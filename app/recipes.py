"""The dinners Sjekka can suggest: ordinary Norwegian weekday food, each made
of ingredients that have a product name in the price data.

An ingredient lists the product names that will do ("Spaghetti" or "Pasta"),
and how much of a usual package a dinner for four uses (`share`: 0.5 is half a
package). The engine in meals.py prices it with the cheapest listed product
that has prices. Things everyone has at home (oil, salt, flour for the
sauce) are `pantry`: shown, not priced. An ingredient marked `minor` may lack
a price without hiding the dinner; the others are what the dinner is."""
from dataclasses import dataclass


@dataclass(frozen=True)
class Ingredient:
    label: str                  # what the dinner needs, "400 g kjøttdeig"
    options: tuple[str, ...]    # product names that will do, in order of preference
    share: float                # of a usual package, for four portions
    minor: bool = False


@dataclass(frozen=True)
class Recipe:
    id: str
    name: str
    blurb: str
    minutes: int
    kind: str                   # the main thing: kjøtt, kylling, svin, fisk, vegetar
    ingredients: tuple[Ingredient, ...]
    pantry: tuple[str, ...]
    steps: tuple[str, ...]


def ing(label: str, *options: str, share: float = 1.0, minor: bool = False) -> Ingredient:
    return Ingredient(label, options, share, minor)


